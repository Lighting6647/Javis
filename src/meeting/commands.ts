/** ชื่อที่ผู้ใช้เรียกก่อนสั่ง ตัดออกก่อนตรวจคำสั่ง */
const NAME = /^(?:จาวิส|จาร์วิส|javis|jarvis)/i;
/** คำขอสุภาพนำหน้าคำสั่ง */
const HEAD = "(?:ช่วย|กรุณา|ขอ)?";
/** สิ่งที่ให้จด */
const SUBJECT = "(?:จด|บันทึก|สรุป)?(?:การ)?ประชุม";
/**
 * หลังคำสั่งมีได้เฉพาะคำลงท้าย เช่น ได้เลย ให้หน่อย ครับ
 * ถ้ามีคำอื่นตาม ถือว่าเป็นประโยคอื่นที่แค่ขึ้นต้นเหมือนกัน เช่น "เริ่มประชุมกี่โมง"
 */
const TAIL = "(?:ได้)?(?:เลย)?(?:ให้)?(?:หน่อย|ที|ด้วย)?(?:นะ)?(?:ครับ|คับ|ค่ะ|คะ|จ้ะ|จ้า)?$";

/** เริ่มหรือเปิด (โหมด) ประชุม ส่วนคำว่าเข้าต้องมีคำว่าโหมดด้วย เพราะ "เข้าประชุม" หมายถึงเข้าร่วมประชุมที่อื่น */
const ENTER_MODE = new RegExp(`^${HEAD}(?:(?:เริ่ม|เปิด)(?:ใช้)?(?:โหมด|mode)?|เข้า(?:สู่)?(?:โหมด|mode))${SUBJECT}${TAIL}`, "i");
/** ขอให้จดการประชุมตรง ๆ */
const TAKE_NOTES = new RegExp(`^${HEAD}(?:จด|บันทึก)(?:การ)?ประชุม${TAIL}`, "i");

/**
 * คำพูดนี้คือคำสั่งให้เริ่มจดการประชุมไหม เช่น "เริ่มโหมดประชุม" หรือ "ช่วยจดการประชุมหน่อย"
 * ตรวจที่หน้าเว็บเองโดยไม่ถาม AI เพราะการเข้าโหมดต้องเกิดทันทีและไม่ควรใช้โควตา
 * รับเฉพาะประโยคที่เป็นคำสั่งทั้งประโยค เพื่อไม่ให้คำถามที่แค่มีคำว่าประชุม (เช่น "พรุ่งนี้มีประชุมกี่โมง") ถูกเข้าใจผิด
 * การจบการประชุมไม่มีคำสั่งเสียง เพราะคำว่า "สรุป" ถูกพูดในการประชุมเป็นปกติ ผู้ใช้กดปุ่มจบเอง
 */
export function isMeetingStartCommand(text: string): boolean {
  const compact = text.replace(/\s+/g, "").replace(NAME, "");
  return ENTER_MODE.test(compact) || TAKE_NOTES.test(compact);
}

import { describe, expect, it } from "vitest";
import { isMeetingStartCommand } from "./commands";

describe("isMeetingStartCommand", () => {
  it.each([
    "เริ่มโหมดประชุม",
    "เริ่มประชุม",
    "เปิดโหมดประชุม",
    "เข้าสู่โหมดประชุม",
    "เข้าโหมดการประชุม",
    "เริ่มโหมดสรุปการประชุม",
    "เริ่มจดการประชุม",
    "เริ่มบันทึกการประชุม",
    "ช่วยจดการประชุมหน่อย",
    "จดประชุมให้ด้วย",
    "บันทึกการประชุม"
  ])("คำสั่งเริ่มจดการประชุม: %s", (text) => {
    expect(isMeetingStartCommand(text)).toBe(true);
  });

  it.each([
    ["มีวรรคระหว่างคำ ตามที่ระบบฟังเสียงมักส่งมา", "เริ่ม โหมด ประชุม"],
    ["เรียกชื่อก่อนสั่ง", "จาวิส เริ่มโหมดประชุม"],
    ["เรียกชื่อเป็นภาษาอังกฤษ", "Javis เริ่มโหมดประชุม"],
    ["คำลงท้ายสุภาพ", "เริ่มโหมดประชุมได้เลยครับ"],
    ["คำขอสุภาพ", "ช่วยเริ่มจดการประชุมให้หน่อยนะคะ"],
    ["ระบบฟังเสียงถอดคำว่าโหมดเป็นภาษาอังกฤษ", "เริ่ม Mode ประชุม"]
  ])("รับคำสั่งที่พูดต่างรูปแบบ: %s", (_reason, text) => {
    expect(isMeetingStartCommand(text)).toBe(true);
  });

  it.each([
    ["ถามเวลาประชุม", "พรุ่งนี้มีประชุมกี่โมง"],
    ["ถามเวลาเริ่มประชุม ซึ่งขึ้นต้นเหมือนคำสั่ง", "เริ่มประชุมกี่โมง"],
    ["ขอเข้าร่วมประชุมออนไลน์ ไม่ใช่ขอให้จด", "เข้าประชุม Zoom ให้หน่อย"],
    ["ถามหาบันทึกเก่า", "บันทึกการประชุมเมื่อวานอยู่ไหน"],
    ["ขอสรุปเรื่องที่ไม่ได้จดไว้", "สรุปการประชุมเมื่อวานให้หน่อย"],
    ["ขอเปิดเว็บ", "เปิดเว็บห้องประชุมออนไลน์"],
    ["ถามความรู้ทั่วไป", "ประชุมผู้ถือหุ้นคืออะไร"],
    ["ข้อความว่าง", "   "]
  ])("ไม่ใช่คำสั่งเริ่มจด จึงส่งให้ AI ตามปกติ: %s", (_reason, text) => {
    expect(isMeetingStartCommand(text)).toBe(false);
  });
});

import { z } from "zod";

/**
 * โหมดสรุปการประชุม: หน้าเว็บจดคำพูดของการประชุมเองทั้งหมดโดยไม่ถาม AI ระหว่างทาง
 * แล้วส่งบันทึกมาให้ AI สรุปครั้งเดียวตอนจบ จึงใช้โควตา AI หนึ่งคำขอต่อการประชุม
 */

/**
 * ความยาวสูงสุดของบันทึกการประชุมที่รับ (ตัวอักษร) พอสำหรับการประชุมราวสองชั่วโมง
 * ต้องตรงกับเพดานที่หน้าเว็บใช้หยุดจด (src/meeting/meetingRecorder.ts) และพอดีกับขนาดคำขอที่ /api/chat รับ (server/app.ts)
 */
export const MAX_TRANSCRIPT_LENGTH = 80_000;

/** เพดานโทเค็นของคำสรุป: ยาวกว่าคำตอบสนทนา เพราะเป็นรายงานหลายหัวข้อ และโมเดลที่มีขั้นคิดนับโทเค็นที่ใช้คิดรวมด้วย */
export const MAX_MEETING_TOKENS = 4000;

export const meetingSchema = z.object({
  /** คำพูดที่จดได้ บรรทัดละช่วงคำพูด ขึ้นต้นด้วยเวลาที่ผ่านไปตั้งแต่เริ่มประชุม */
  transcript: z.string().trim().min(1).max(MAX_TRANSCRIPT_LENGTH),
  /** ความยาวของการประชุมเป็นนาที */
  minutes: z
    .number()
    .int()
    .min(0)
    .max(24 * 60)
    .optional()
});

export type MeetingRequest = z.infer<typeof meetingSchema>;

const OPEN_TAG = "<บันทึกการประชุม>";
const CLOSE_TAG = "</บันทึกการประชุม>";

/**
 * คำสั่งระบบของการสรุปการประชุม ใช้แทนคำสั่งของการสนทนาปกติทั้งชุด
 * คำสรุปถูกแสดงบนจอ ไม่ได้อ่านออกเสียง จึงเขียนเป็นรายงานมีหัวข้อได้ แต่หน้าจอแสดงได้เฉพาะข้อความธรรมดา
 */

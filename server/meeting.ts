/** ข้อความของผู้ใช้ที่ส่งให้ AI: บันทึกการประชุมในขอบเขตที่ชัดเจน เพื่อให้แยกจากคำสั่งได้ */
export function buildMeetingPrompt({ transcript, minutes }: MeetingRequest): string {
  const length = minutes !== undefined && minutes > 0 ? ` การประชุมยาวประมาณ ${minutes} นาที` : "";
  // ข้อความในบันทึกที่เลียนแบบขอบเขตปิด ต้องไม่ทำให้บันทึกจบก่อนเวลา
  const body = transcript.replaceAll(CLOSE_TAG, "").replaceAll(OPEN_TAG, "");
  return `สรุปการประชุมจากบันทึกคำพูดต่อไปนี้${length}\n${OPEN_TAG}\n${body}\n${CLOSE_TAG}`;
}

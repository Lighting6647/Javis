import { describe, expect, it } from "vitest";
import { MAX_SELECTED_MEMORIES, scoreMemories, selectRelevantMemories, tokenize } from "./memoryRelevance.js";

/** ความจำจริงของผู้ใช้หนึ่งคน 30 เรื่อง เรียงตามเวลาที่จำ */
const TEXTS = [
  "ผู้ใช้ชื่อไลท์ ให้เรียกว่าคุณไลท์",
  "ผู้ใช้ชอบให้ตอบสั้นและตรงประเด็น",
  "ผู้ใช้ทำงานด้านไอทีและปัญญาประดิษฐ์",
  "ผู้ใช้ชอบดื่มกาแฟดำไม่ใส่น้ำตาล",
  "ผู้ใช้แพ้กุ้งและอาหารทะเล",
  "ผู้ใช้มีแมวชื่อมะลิ",
  "ผู้ใช้วิ่งจ็อกกิ้งที่สวนลุมทุกเช้าวันเสาร์",
  "ผู้ใช้ใช้รถยนต์ไฟฟ้า BYD Atto 3",
  "ผู้ใช้กำลังเรียนภาษาญี่ปุ่นระดับ N4",
  "ผู้ใช้ชอบฟังเพลงแจ๊สตอนทำงาน",
  "ผู้ใช้อาศัยอยู่ย่านบางนา กรุงเทพฯ",
  "ลูกสาวของผู้ใช้เรียนอยู่ชั้น ป.3",
  "ผู้ใช้ประชุมทีมทุกวันจันทร์ 10 โมง",
  "ผู้ใช้กำลังพัฒนาแอปผู้ช่วยเสียงชื่อเดลลูน่า",
  "ผู้ใช้ใช้ Vercel และ Neon สำหรับโปรเจกต์ส่วนตัว",
  "ผู้ใช้ไม่ทานเนื้อวัว",
  "ผู้ใช้ชอบอ่านหนังสือแนววิทยาศาสตร์",
  "ผู้ใช้มีนัดหมอฟันทุกหกเดือน",
  "ผู้ใช้ลงทุนในกองทุนรวมดัชนี",
  "ผู้ใช้เล่นกีตาร์เป็นงานอดิเรก",
  "ผู้ใช้วางแผนไปเที่ยวญี่ปุ่นเดือนเมษายน",
  "ผู้ใช้ชอบปลูกต้นไม้ในคอนโด",
  "ผู้ใช้ใช้ iPhone และ MacBook",
  "ผู้ใช้นอนดึกประมาณเที่ยงคืน",
  "แม่ของผู้ใช้อยู่เชียงใหม่",
  "ผู้ใช้ชอบอาหารเผ็ด",
  "ผู้ใช้ทำงานแบบไฮบริด เข้าออฟฟิศวันอังคารและพฤหัส",
  "ผู้ใช้กำลังลดน้ำหนักด้วยการนับแคลอรี",
  "ผู้ใช้ชอบดูฟุตบอลพรีเมียร์ลีก เชียร์ลิเวอร์พูล",
  "ผู้ใช้เพิ่งซื้อหูฟังตัดเสียงรบกวน"
];
const memories = TEXTS.map((text, index) => ({ id: `m${index.toString(36)}`, text }));
const pick = (query: string) => selectRelevantMemories(memories, query).map((memory) => memory.text);

describe("tokenize", () => {
  it("ตัดคำภาษาไทยและตัดคำทั่วไปออก", () => {
    expect(tokenize("วันนี้ควรดื่มกาแฟไหมครับ")).toEqual(["ดื่ม", "กาแฟ"]);
    expect(tokenize("Deploy to Vercel")).toEqual(["deploy", "vercel"]);
  });
});

describe("selectRelevantMemories", () => {
  it("ไม่เกิน 20 เรื่อง: ส่งทั้งหมดตามเดิม", () => {
    const few = memories.slice(0, 20);
    expect(selectRelevantMemories(few, "อะไรก็ได้")).toEqual(few);
    expect(selectRelevantMemories(undefined, "x")).toEqual([]);
  });

  it("เกิน 20 เรื่อง: ส่งไม่เกิน 15 เรื่อง เรียงลำดับเดิม", () => {
    const selected = selectRelevantMemories(memories, "แนะนำเมนูกาแฟหน่อย");
    expect(selected.length).toBeLessThanOrEqual(MAX_SELECTED_MEMORIES);
    expect(selected.map((memory) => memory.id)).toEqual([...selected].sort((a, b) => TEXTS.indexOf(a.text) - TEXTS.indexOf(b.text)).map((memory) => memory.id));
  });

  it("ส่งความจำพื้นฐานเสมอ: ชื่อที่ให้เรียกและวิธีตอบ", () => {
    const selected = pick("พรุ่งนี้ฝนตกไหม");
    expect(selected).toContain("ผู้ใช้ชื่อไลท์ ให้เรียกว่าคุณไลท์");
    expect(selected).toContain("ผู้ใช้ชอบให้ตอบสั้นและตรงประเด็น");
  });

  it("ส่งเรื่องล่าสุดสามเรื่องเสมอ", () => {
    expect(pick("พรุ่งนี้ฝนตกไหม")).toEqual(expect.arrayContaining(TEXTS.slice(-3)));
  });

  it.each([
    ["แนะนำร้านอาหารทะเลแถวบางนาหน่อย", ["ผู้ใช้แพ้กุ้งและอาหารทะเล", "ผู้ใช้อาศัยอยู่ย่านบางนา กรุงเทพฯ"]],
    ["ไปญี่ปุ่นควรเตรียมอะไรบ้าง", ["ผู้ใช้วางแผนไปเที่ยวญี่ปุ่นเดือนเมษายน", "ผู้ใช้กำลังเรียนภาษาญี่ปุ่นระดับ N4"]],
    ["ช่วยเตือนเรื่องประชุมวันจันทร์", ["ผู้ใช้ประชุมทีมทุกวันจันทร์ 10 โมง"]],
    ["แมวไม่ยอมกินข้าวทำยังไงดี", ["ผู้ใช้มีแมวชื่อมะลิ"]],
    ["deploy ขึ้น vercel แล้วต่อ neon ยังไง", ["ผู้ใช้ใช้ Vercel และ Neon สำหรับโปรเจกต์ส่วนตัว"]],
    ["คืนนี้ลิเวอร์พูลเตะกี่โมง", ["ผู้ใช้ชอบดูฟุตบอลพรีเมียร์ลีก เชียร์ลิเวอร์พูล"]]
  ])("คำถาม \"%s\" ได้ความจำที่เกี่ยวข้อง", (query, expected) => {
    expect(pick(query)).toEqual(expect.arrayContaining(expected));
  });

  it("ไม่ส่งเรื่องที่ไม่เกี่ยวกับคำถามเลย", () => {
    const selected = pick("แมวไม่ยอมกินข้าวทำยังไงดี");
    expect(selected).not.toContain("ผู้ใช้ลงทุนในกองทุนรวมดัชนี");
    expect(selected).not.toContain("ผู้ใช้เล่นกีตาร์เป็นงานอดิเรก");
  });

  it("สั่งลืมเรื่องเก่า: ความจำเรื่องนั้นถูกส่งไปให้ AI ลบด้วยรหัสได้", () => {
    expect(pick("ลืมเรื่องหมอฟันไปได้เลย")).toContain("ผู้ใช้มีนัดหมอฟันทุกหกเดือน");
  });
});

describe("scoreMemories", () => {
  it("คำที่หายากได้คะแนนมากกว่าคำที่อยู่ในทุกเรื่อง", () => {
    const [specific, generic] = scoreMemories([{ id: "m1", text: "ผู้ใช้ชอบกาแฟ" }, { id: "m2", text: "ผู้ใช้ชอบชา" }], "กาแฟ");
    expect(specific).toBeGreaterThan(generic ?? 0);
  });
});
